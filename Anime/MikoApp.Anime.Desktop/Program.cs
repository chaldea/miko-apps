#if DEBUG
using Miko.DevTools;
#endif
using Miko.Windowing;
using Miko.Windowing.Native;
using Miko.Windowing.Video;
using MikoApp.Anime;

namespace MikoApp.Anime.Desktop;

public static class Program
{
    [STAThread]
    public static void Main(string[] args)
    {
        var context = App.CreateContext(builder =>
        {
            builder.UseDesktopNative();
            builder.UseSystemVideo();
#if DEBUG
            // F12 opens the DevTools inspector (DOM, styles, resources, logs). It is a
            // debugging aid: Release builds do not reference Miko.DevTools at all.
            builder.AddDevTools();
#endif
        });

        // Hot reload is wired up inside the shared app assembly, where the
        // handler is generated by Miko.Razor.Compiler.
        App.InitializeHotReload(context);
        DesktopIcon.Configure(context);

        context.RunDesktop();
    }
}
